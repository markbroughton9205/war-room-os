#!/usr/bin/env node
/**
 * Generates lib/native-builder/blueprint/embeddedTools.generated.ts from the host-owned tool scripts, so a bundled/standalone runtime does not depend on
 * import.meta.url or file tracing to find them: the service materializes (and hash-pins) them under the blueprint data root at start.
 * `node scripts/generate-blueprint-embedded.mjs --check` verifies the committed file is current (used by validate:blueprint).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'lib', 'native-builder', 'blueprint')
const SOURCES = { 'depprobe.mjs': 'depprobe.mjs', 'wr-bundle-build.mjs': 'recipes/wr-bundle-build.mjs', 'wr-bundle-pack.mjs': 'recipes/wr-bundle-pack.mjs' }
const sha = b => createHash('sha256').update(b).digest('hex')
let out = '// GENERATED by scripts/generate-blueprint-embedded.mjs - do not edit. Sources: lib/native-builder/blueprint/{depprobe.mjs,recipes/*.mjs}\n'
out += 'export const EMBEDDED_TOOLS: Readonly<Record<string, { source: string; sha256: string }>> = {\n'
for (const [name, rel] of Object.entries(SOURCES)) { const src = fs.readFileSync(path.join(dir, rel), 'utf8'); out += `  ${JSON.stringify(name)}: { sha256: ${JSON.stringify(sha(Buffer.from(src)))}, source: ${JSON.stringify(src)} },\n` }
out += '}\n'
const target = path.join(dir, 'embeddedTools.generated.ts')
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (cur !== out) { console.error('embeddedTools.generated.ts is stale: run node scripts/generate-blueprint-embedded.mjs'); process.exit(1) }
  console.log('embedded tools current'); process.exit(0)
}
fs.writeFileSync(target, out); console.log(`wrote ${path.relative(root, target)}`)
