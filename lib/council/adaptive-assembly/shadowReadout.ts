import type { CouncilOrchestrationFamily } from '@/components/council/councilSessionTypes'
import type {
  CouncilShadowSelectionReport,
  RecommendationMatchStatus,
  SynthesizerMatchStatus,
} from './shadowTypes'

export type FamilyDisplayItem = {
  readonly id: string
  readonly label: string
  readonly known: boolean
}

export type RecommendationReasonView = {
  readonly label: string
  readonly text: string
}

export type AdaptiveCouncilReadoutStatus =
  | RecommendationMatchStatus
  | 'shadow_failed'

export type AdaptiveCouncilReadoutSynthesizerStatus =
  | 'match'
  | 'mismatch'
  | 'actual_unresolved'
  | 'recommendation_unresolved'
  | 'not_comparable'

export type AdaptiveCouncilReadoutViewModel = {
  readonly available: boolean
  readonly status: AdaptiveCouncilReadoutStatus
  readonly statusLabel: string
  readonly statusExplanation: string
  readonly advisoryOnly: true
  readonly executionUnaffected: boolean
  readonly recommendedFamilies: readonly FamilyDisplayItem[]
  readonly actualFamilies: readonly FamilyDisplayItem[]
  readonly overlappingFamilies: readonly FamilyDisplayItem[]
  readonly recommendedOnlyFamilies: readonly FamilyDisplayItem[]
  readonly actualOnlyFamilies: readonly FamilyDisplayItem[]
  readonly recommendationReasons: readonly RecommendationReasonView[]
  readonly capabilitiesRequested: readonly string[]
  readonly capabilitiesCovered: readonly string[]
  readonly unresolvedCapabilities: readonly string[]
  readonly evidenceRequired: boolean | null
  readonly liveDataRequired: boolean | null
  readonly recommendedRedTeam: boolean | null
  readonly actualRedTeamIncluded: boolean | null
  readonly recommendedSynthesizer: FamilyDisplayItem | null
  readonly actualSynthesizer: FamilyDisplayItem | null
  readonly synthesizerStatus: AdaptiveCouncilReadoutSynthesizerStatus
  readonly recommendationVersion: string | null
  readonly generatedAt: string | null
  readonly uncertaintyMessages: readonly string[]
  readonly failureMessage: string | null
  readonly sourceLabel: 'Generated by Adaptive Council shadow planning'
}

export type AdaptiveCouncilReadoutEligibilityInput = {
  readonly messageType: string
  readonly responseComplete: boolean
  readonly isUserMessage: boolean
}

